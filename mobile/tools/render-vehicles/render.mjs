/**
 * Renders the 3D vehicle models (Kenney Car Kit, CC0) into the PNG pictures
 * the app uses:
 *   assets/vehicles/<type>.png      three-quarter view (cards, picker)   384 px
 *   assets/vehicles/<type>-top.png  straight from above (map marker)     192 px
 * and writes src/lib/vehicleSprites.ts (the map pictures as data URIs, because
 * the map runs inside a WebView).
 *
 *   node tools/render-vehicles/render.mjs
 *
 * Needs: devDependency "three" and Google Chrome (headless, software WebGL).
 */
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '../..');
const KIT = 'kenney_car-kit/Models/GLB format';
// Our vehicle type -> model file (+ turn in degrees if the model faces another way).
export const MODELS = {
  car: { file: 'sedan.glb' },
  van: { file: 'van.glb' },
  truck: { file: 'delivery.glb' }, // box truck (truck.glb is a pickup)
  tractor: { file: 'tractor.glb' },
};
const OUT = path.join(ROOT, 'assets/vehicles');
fs.mkdirSync(OUT, { recursive: true });

const jobs = [];
for (const [type, m] of Object.entries(MODELS)) {
  const model = `/${KIT}/${m.file}`.replace(/ /g, '%20');
  jobs.push({ model, out: `${type}.png`, view: 'card', size: 384, yaw: m.yaw || 0 });
  jobs.push({ model, out: `${type}-top.png`, view: 'top', size: 192, yaw: m.yaw || 0 });
}

const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json', '.glb': 'model/gltf-binary', '.png': 'image/png' };
let chrome;
const server = http.createServer((req, res) => {
  const url = new URL(req.url, 'http://x');
  if (req.method === 'POST') {
    let body = '';
    req.on('data', (c) => (body += c));
    req.on('end', () => {
      if (url.pathname === '/save') {
        const name = path.basename(url.searchParams.get('name'));
        fs.writeFileSync(path.join(OUT, name), Buffer.from(body.split(',')[1], 'base64'));
        console.log('  saved', name);
      } else if (url.pathname === '/log') {
        console.error('  ERROR', body);
      } else if (url.pathname === '/done') {
        finish();
      }
      res.end('ok');
    });
    return;
  }
  if (url.pathname === '/jobs.json') return res.end(JSON.stringify(jobs));
  const file = url.pathname === '/' ? path.join(import.meta.dirname, 'page.html') : path.join(ROOT, decodeURIComponent(url.pathname));
  if (!file.startsWith(ROOT) || !fs.existsSync(file)) {
    res.statusCode = 404;
    return res.end();
  }
  res.setHeader('content-type', TYPES[path.extname(file)] || 'application/octet-stream');
  fs.createReadStream(file).pipe(res);
});

server.listen(0, '127.0.0.1', () => {
  const { port } = server.address();
  console.log(`rendering ${jobs.length} pictures…`);
  chrome = spawn('google-chrome', [
    '--headless=new', '--no-sandbox', '--disable-gpu-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader',
    '--hide-scrollbars', `--user-data-dir=${fs.mkdtempSync(path.join(process.env.TMPDIR || '/tmp', 'render-'))}`,
    '--remote-debugging-port=0', `http://127.0.0.1:${port}/`,
    '--enable-logging=stderr', '--v=0',
  ], { stdio: ['ignore', 'ignore', process.env.DEBUG_RENDER ? 'inherit' : 'ignore'] });
  setTimeout(() => { console.error('timed out'); finish(1); }, Number(process.env.RENDER_TIMEOUT_MS || 120_000)).unref();
});

function finish(code = 0) {
  chrome?.kill();
  server.close();
  // Map pictures as data URIs for the WebView map.
  const sprites = Object.fromEntries(
    Object.keys(MODELS)
      .filter((t) => fs.existsSync(path.join(OUT, `${t}-top.png`)))
      .map((t) => [t, 'data:image/png;base64,' + fs.readFileSync(path.join(OUT, `${t}-top.png`)).toString('base64')])
  );
  fs.writeFileSync(
    path.join(ROOT, 'src/lib/vehicleSprites.ts'),
    '// GENERATED by tools/render-vehicles/render.mjs — do not edit.\n' +
      '// Top-down 3D renders (Kenney Car Kit, CC0) used as map markers; they rotate with the heading.\n' +
      `export const VEHICLE_SPRITES: Record<string, string> = ${JSON.stringify(sprites, null, 2)};\n\n` +
      '// Three-quarter 3D renders for cards and the vehicle picker.\n' +
      'export const VEHICLE_IMAGES: Record<string, number> = {\n' +
      Object.keys(sprites).map((t) => `  ${t}: require('../../assets/vehicles/${t}.png'),`).join('\n') +
      '\n};\n'
  );
  console.log('wrote src/lib/vehicleSprites.ts');
  process.exit(code);
}
